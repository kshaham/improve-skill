def import_graph(con, include_deferred=False):
    graph = {}
    query = "SELECT src_path, dst_path FROM code_edge WHERE rel='imports'" + ("" if include_deferred else " AND deferred=0")
    for src, dst in con.execute(query):
        if src != dst:
            graph.setdefault(src, set()).add(dst)
    return {node: sorted(targets) for node, targets in graph.items()}


def find_cycles(con, max_length=5, limit=50, include_deferred=False, work=CYCLE_WORK):
    """Import cycles of up to `max_length` files, shortest first, each reported once (rotations
    removed). Lengths are searched in increasing order and the search stops once `limit` cycles
    are found or after `work` steps, so a dense import graph (millions of cycles) answers
    quickly; `complete` says whether every cycle was counted. Imports inside functions and
    `TYPE_CHECKING` blocks are the usual way to break a cycle, so they are left out unless
    `include_deferred`."""
    graph = import_graph(con, include_deferred)
    found, steps, complete = [], 0, True
    seen = set()
    for length in range(2, max(2, int(max_length)) + 1):
        for start in sorted(graph):
            stack = [(start, (start,))]
            while stack:
                steps += 1
                if steps > work or len(found) >= limit:
                    complete = False
                    break
                node, path = stack.pop()
                for following in reversed(graph.get(node, ())):
                    if following == start and len(path) == length:
                        if path not in seen:
                            seen.add(path)
                            found.append(path)
                    elif following > start and following not in path and len(path) < length:
                        stack.append((following, path + (following,)))
            if not complete:
                break
        if not complete:
            break
    rows = [{"length": len(cycle), "files": list(cycle)} for cycle in found[:limit]]
    return {"cycles": rows, "found": len(found), "complete": complete}


def cycles(con, max_length=5, limit=50, include_deferred=False):
    """(cycles, how many were found): the compact form of `find_cycles`."""
    result = find_cycles(con, max_length, limit, include_deferred)
    return result["cycles"], result["found"]


def degrees(con):
    """Per file: how many files depend on it, how many it depends on, and how many symbols it has."""
    result = {}
    for path, count in con.execute("SELECT dst_path, count(DISTINCT src_path) FROM code_edge "
                                   "WHERE src_path != dst_path GROUP BY dst_path"):
        result.setdefault(path, {})["used_by"] = count
    for path, count in con.execute("SELECT src_path, count(DISTINCT dst_path) FROM code_edge "
                                   "WHERE src_path != dst_path GROUP BY src_path"):
        result.setdefault(path, {})["uses"] = count
    for path, count in con.execute("SELECT path, count(*) FROM code_symbol WHERE kind != 'module' GROUP BY path"):
        result.setdefault(path, {})["symbols"] = count
    return result


def file_edges(con):
    """Undirected file-to-file weights from resolved code edges (for grouping)."""
    weights = {}
    for src, dst, count in con.execute("SELECT src_path, dst_path, count(*) FROM code_edge WHERE src_path != dst_path "
                                       "GROUP BY src_path, dst_path"):
        key = (src, dst) if src < dst else (dst, src)
        weights[key] = weights.get(key, 0) + count
    return weights


