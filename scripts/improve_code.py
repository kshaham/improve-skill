def combine(found, via):
    """A resolution reached through another one is only as certain as its weakest step."""
    if found is None or via is None:
        return found
    tier = INFERRED if INFERRED in (found[3], via[3]) else OBSERVED
    return (found[0], found[1], min(found[2], via[2]), tier)


def agree(targets):
    """One target when every candidate names the same thing; otherwise nothing."""
    if not targets or any(target is None for target in targets):
        return None
    if len({(target[0], target[1]) for target in targets}) != 1:
        return None
    return min(targets, key=lambda target: -target[2])


class Resolver:
    """Every stored fact, indexed for lookup. Targets are ("symbol", id, confidence, tier) or
    ("module", path, confidence, tier)."""

    def __init__(self, con):
        self.files, self.exports, self.generated = {}, {}, set()
        modules_by_file = {}
        for path, lang, module, made, exports in con.execute(
                "SELECT path, lang, module, generated, exports FROM code_file"):
            self.files[path] = lang
            modules_by_file[path] = module
            if made:
                self.generated.add(path)
            if exports:
                self.exports[path] = json.loads(exports)
        python = [path for path, lang in self.files.items() if lang == "python"]
        packages = package_directories(python)
        stems = {path[:-3] for path in python if path.endswith(".py")}
        self.modules = {}
        for path in python:
            if path.endswith(".pyi") and path[:-4] in stems:
                continue  # A stub beside its module names the same module.
            for name in module_aliases(path, packages):
                self.modules.setdefault(name, set()).add(path)
        self.symbols, self.top, self.by_name, self.fixtures = {}, {}, {}, {}
        jvm_types = []
        for symbol_id, path, name, qualname, kind, flags in con.execute(
                "SELECT id, path, name, qualname, kind, flags FROM code_symbol"):
            self.symbols[symbol_id] = (path, name, qualname, kind)
            if kind in ("class", "function") and "." not in qualname:
                self.top[(path, name)] = symbol_id
                if self.files.get(path) == "python" and path not in self.generated:
                    self.by_name.setdefault(name, []).append(symbol_id)
            if flags == "fixture":
                self.fixtures.setdefault(name, []).append(symbol_id)
            if kind == "class" and self.files.get(path) in ("java", "kotlin") and modules_by_file.get(path) is not None:
                jvm_types.append(((modules_by_file[path] + "." if modules_by_file[path] else "") + name, path))
        for path, lang in self.files.items():
            if lang in ("java", "kotlin"):
                stem = posixpath.splitext(posixpath.basename(path))[0]
                package = modules_by_file.get(path) or ""
                jvm_types.append(((package + "." if package else "") + stem, path))
        self.import_rows = con.execute("SELECT path, alias, module, name, level, line, deferred, scope, style, export "
                                       "FROM code_import ORDER BY rowid").fetchall()
        self.imports, self.stars, self.js_exports, self.js_stars = {}, {}, {}, {}
        for row in self.import_rows:
            path, alias, module, name, level, line, deferred, scope, style, export = row
            if style == "py":
                if alias == "*":
                    if not deferred:
                        self.stars.setdefault(path, []).append(row)
                else:
                    self.imports.setdefault((path, scope or ""), {}).setdefault(alias, []).append(row)
            elif style == "js":
                if export and alias == "*":
                    self.js_stars.setdefault(path, []).append(row)
                elif export:
                    self.js_exports.setdefault(path, {}).setdefault(alias, []).append(row)
                elif alias:
                    self.imports.setdefault((path, ""), {}).setdefault(alias, []).append(row)
        self.attributes = {}
        for path, owner, attribute, kind, scope, head, rest in con.execute(
                "SELECT path, owner, attr, kind, scope, head, rest FROM code_attr"):
            self.attributes.setdefault(f"{path}::{owner}", {})[attribute] = (kind, scope, head, rest)
        config = json.loads(meta_get(con, "config", "{}") or "{}")
        self.languages = lang_module.LanguageResolver(set(self.files), config, jvm_types)
        self.bases = {}
        self.export_memo, self.module_memo, self.script_memo = {}, {}, {}

    # ---- modules

    def python_module(self, importer, module, level):
        """The file an import names, or None (third-party and standard-library imports, or a
        name several files could be)."""
        key = (posixpath.dirname(importer), module, level)  # Only the importer's directory matters.
        if key not in self.module_memo:
            self.module_memo[key] = self.find_python_module(importer, module, level)
        return self.module_memo[key]

    def find_python_module(self, importer, module, level):
        if level and level > 0:
            package = posixpath.dirname(importer)  # The importer's package, for a module or an __init__.
            for _ in range(level - 1):
                package = posixpath.dirname(package)
            base = (package + "/" if package else "") + module.replace(".", "/") if module else package
            for candidate in (base + ".py", base + "/__init__.py", base + ".pyi", base + "/__init__.pyi"):
                if candidate.strip("/") in self.files:
                    return candidate.strip("/")
            return None
        if not module:
            return None
        found = self.modules.get(module, set())
        if len(found) == 1:
            return next(iter(found))
        # Script-style imports: a module beside the importer (the script's directory is on sys.path).
        directory = posixpath.dirname(importer)
        prefix = directory + "/" if directory else ""
        stem = module.replace(".", "/")
        for candidate in (prefix + stem + ".py", prefix + stem + "/__init__.py", prefix + stem + ".pyi"):
            if candidate in self.files:
                return candidate
        if len(found) > 1:
            hinted = [path for path in found if any(path.startswith(root + stem) for root in SOURCE_ROOTS)]
            return hinted[0] if len(hinted) == 1 else None
        return None

    def script(self, importer, spec):
        key = (importer, spec)
        if key not in self.script_memo:
            self.script_memo[key] = self.languages.script(importer, spec)
        return self.script_memo[key]

    # ---- names a module provides

    def export(self, path, name, hops=0):
        """What `name` means as an attribute of the module in `path`: its own definition, a name
        it imports (re-exports, followed up to MAX_HOPS), a star import, or a submodule."""
        key = (path, name)
        if key in self.export_memo:
            return self.export_memo[key]
        self.export_memo[key] = None  # A re-export cycle resolves to nothing.
        found = self.find_export(path, name, hops) if hops <= MAX_HOPS else None
        self.export_memo[key] = found
        return found

    def find_export(self, path, name, hops):
        symbol = self.top.get((path, name))
        if symbol:
            return ("symbol", symbol, 1.0, OBSERVED)
        lang = self.files.get(path)
        if lang == "python":
            rows = [row for row in self.imports.get((path, ""), {}).get(name, []) if not row[6]]
            if rows:
                return agree([self.import_target(path, row, [], hops + 1)[0] for row in rows])
            found = self.star_export(path, name, hops)
            if found:
                return found
            if posixpath.basename(path) in ("__init__.py", "__init__.pyi"):
                submodule = self.python_module(path, name, 1)
                if submodule:
                    return ("module", submodule, 1.0, OBSERVED)
            return None
        if lang in ("javascript", "typescript"):
            rows = self.js_exports.get(path, {}).get(name, [])
            if rows:
                return agree([self.js_reexport(path, row, hops + 1) for row in rows])
            found = [self.export(target, name, hops + 1) for target in
                     (self.script(path, row[2]) for row in self.js_stars.get(path, [])) if target]
            found = [target for target in found if target]
            return found[0] if len({target[1] for target in found}) == 1 else None
        return None

    def js_reexport(self, path, row, hops):
        _, alias, module, name = row[:4]
        if module is None:
            symbol = self.top.get((path, name))
            return ("symbol", symbol, 1.0, OBSERVED) if symbol else None
        target = self.script(path, module)
        if target is None:
            return None
        return ("module", target, 1.0, OBSERVED) if name == "*" else self.export(target, name, hops)

    def star_export(self, path, name, hops=0):
        """A name provided by the module's star imports: exactly one source must provide it, and
        every source must be in the repository (a third-party star import could provide it too)."""
        rows = self.stars.get(path, [])
        if not rows:
            return None
        found = []
        for row in rows:
            source = self.python_module(path, row[2], row[4])
            if source is None:
                return None
            allowed = self.exports.get(source)
            if allowed == "dynamic":
                return None
            if (name in allowed) if isinstance(allowed, list) else not name.startswith("_"):
                target = self.export(source, name, hops + 1)
                if target:
                    found.append(target)
        return found[0] if len({target[1] for target in found}) == 1 else None

    def import_target(self, path, row, rest, hops=0):
        """(target, parts of `rest` consumed) for one import row bound to a name."""
        _, alias, module, name, level, _, _, _, style, _ = row
        if style == "js":
            target = self.script(path, module)
            if target is None or name is None:
                return None, 0
            if name == "*":
                return ("module", target, 1.0, OBSERVED), 0
            return self.export(target, name, hops), 0
        if name is None:
            if "." in module and alias == module.split(".")[0]:
                # `import a.b` binds `a`; `a.b.f()` names the submodule.
                for size in range(len(rest), -1, -1):
                    target = self.python_module(path, ".".join([alias] + list(rest[:size])), 0)
                    if target:
                        return ("module", target, 1.0, OBSERVED), size
                return None, 0
            target = self.python_module(path, module, level)
            return (("module", target, 1.0, OBSERVED) if target else None), 0
        source = self.python_module(path, module, level) if module or level else None
        found = self.export(source, name, hops) if source else None
        if found is None:
            submodule = self.python_module(path, (module + "." if module else "") + name, level)
            found = ("module", submodule, 1.0, OBSERVED) if submodule else None
        return found, 0

    # ---- references

    def head(self, path, kind, scope, name, rest):
        """(target, parts of `rest` consumed) for the head name of a reference."""
        if kind == "def":
            symbol = self.top.get((path, name))
            return (("symbol", symbol, 1.0, OBSERVED) if symbol else None), 0
        if kind == "nested":
            symbol = f"{path}::{name}"
            return (("symbol", symbol, 1.0, OBSERVED) if symbol in self.symbols else None), 0
        if kind == "import":
            rows = self.imports.get((path, scope or ""), {}).get(name, [])
            results = [self.import_target(path, row, rest) for row in rows]
            if not results or any(target is None for target, _ in results):
                return None, 0
            if len({(target[0], target[1], consumed) for target, consumed in results}) != 1:
                return None, 0
            return results[0]
        if kind == "free":
            found = self.star_export(path, name)
            if found:
                return found, 0
            if self.stars.get(path):
                # The star imports decide what an unbound name is; one they do not provide is a
                # NameError or comes from outside the repository, never a repository-wide guess.
                return None, 0
            return (self.infer(path, name) if not rest else None), 0
        return None, 0

    def step(self, target, name):
        if target[0] == "module":
            return combine(self.export(target[1], name), target)
        if self.symbols[target[1]][3] == "class":
            return combine(self.member(target[1], name), target)
        return None

    def reference(self, path, kind, scope, head, rest, attr):
        """The symbol one stored reference names, or None: never a guess."""
        if kind in ("self", "super", "selfattr"):
            owner = f"{path}::{head}"
            if owner not in self.symbols:
                return None
            if kind == "self":
                return self.member(owner, attr) if attr else ("symbol", owner, 1.0, OBSERVED)
            if kind == "super":
                return self.inherited(owner, attr)
            made = self.attribute_class(owner, rest)
            return combine(self.member(made[1], attr), made) if made else None
        if kind == "fixture":
            return self.fixture(path, head)
        parts = rest.split(".") if rest else []
        target, consumed = self.head(path, kind, scope, head, parts)
        for part in parts[consumed:]:
            if target is None:
                return None
            target = self.step(target, part)
        if target is None or target[0] != "symbol":
            return None
        if attr is not None:
            if self.symbols[target[1]][3] != "class":
                return None
            return combine(self.member(target[1], attr), target)
        return target

    def member(self, cls, name, depth=0):
        """A method or nested class of a class, or the one its bases provide (single-inheritance
        walk; two different bases providing it is refused)."""
        symbol = f"{cls}.{name}"
        if symbol in self.symbols:
            return ("symbol", symbol, 1.0, OBSERVED)
        return self.inherited(cls, name, depth)

    def inherited(self, cls, name, depth=0):
        if depth >= MAX_MRO:
            return None
        found = []
        for base in self.bases.get(cls, []):
            hit = self.member(base[1], name, depth + 1)
            if hit:
                found.append(combine(hit, base))
        return found[0] if len({hit[1] for hit in found}) == 1 else None

    def attribute_class(self, owner, attribute, depth=0):
        """The class of `self.attribute` in `owner` or the base that assigns it."""
        row = self.attributes.get(owner, {}).get(attribute)
        if row is not None:
            if row[0] is None:
                return None
            target = self.reference(self.symbols[owner][0], row[0], row[1], row[2], row[3], None)
            return target if target and self.symbols[target[1]][3] == "class" else None
        if depth >= MAX_MRO:
            return None
        found = [combine(self.attribute_class(base[1], attribute, depth + 1), base) for base in self.bases.get(owner, [])]
        found = [target for target in found if target]
        return found[0] if len({target[1] for target in found}) == 1 else None

    def fixture(self, path, name):
        """pytest's rule: a fixture in the test's own file, else the nearest conftest.py above it."""
        candidates = self.fixtures.get(name, [])
        if not candidates:
            return None
        here = [symbol for symbol in candidates if self.symbols[symbol][0] == path]
        if here:
            return ("symbol", here[0], 1.0, OBSERVED) if len(here) == 1 else None
        directory = posixpath.dirname(path)
        while True:
            conftest = (directory + "/" if directory else "") + "conftest.py"
            found = [symbol for symbol in candidates if self.symbols[symbol][0] == conftest]
            if found:
                return ("symbol", found[0], 1.0, OBSERVED) if len(found) == 1 else None
            if not directory:
                return None
            directory = posixpath.dirname(directory)

    def infer(self, path, name):
        """A name bound nowhere in its module: defined exactly once in the repository (0.85), once
        among tests for a test or among non-tests otherwise (0.75), or, for a test, in the one
        nearest test file (0.6). Anything else is not linked."""
        candidates = self.by_name.get(name, [])
        if len(candidates) == 1:
            return ("symbol", candidates[0], 0.85, INFERRED)
        if not candidates:
            return None
        caller_test = is_test(path)
        pool = [symbol for symbol in candidates if is_test(self.symbols[symbol][0]) == caller_test]
        if len(pool) == 1:
            return ("symbol", pool[0], 0.75, INFERRED)
        if caller_test and pool:
            ranked = sorted(((shared_depth(path, self.symbols[symbol][0]), symbol) for symbol in pool), reverse=True)
            if ranked[0][0] > ranked[1][0]:
                return ("symbol", ranked[0][1], 0.6, INFERRED)
        return None


def shared_depth(left, right):
    count = 0
    for a, b in zip(posixpath.dirname(left).split("/"), posixpath.dirname(right).split("/")):
        if a != b:
            break
        count += 1
    return count


class EdgeSet:
    """Resolved edges keyed by (src, rel, dst); every site is counted, the first few lines kept."""

    def __init__(self):
        self.edges = {}

    def add(self, src, rel, dst, src_path, dst_path, line, confidence, tier, deferred=0):
        entry = self.edges.get((src, rel, dst))
        if entry is None:
            self.edges[(src, rel, dst)] = [src_path, dst_path, line, confidence, tier, deferred, 1, [line]]
            return
        entry[6] += 1
        if line not in entry[7] and len(entry[7]) < MAX_SITE_LINES:
            entry[7].append(line)
        entry[2] = min(entry[2], line)
        entry[5] = min(entry[5], deferred)  # An import is deferred only if every instance of it is.
        if confidence > entry[3]:
            entry[3], entry[4] = confidence, tier

    def rows(self):
        return [(src, rel, dst, *value[:6], value[6], ",".join(str(line) for line in sorted(value[7])))
                for (src, rel, dst), value in sorted(self.edges.items())]


def resolve(con):
    """Recompute every resolved edge from the stored facts; returns the edge count."""
    resolver = Resolver(con)
    edges = EdgeSet()
    for row in resolver.import_rows:
        import_edges(resolver, edges, row)
    references = con.execute("SELECT path, caller, rel, kind, scope, head, rest, attr, line FROM code_call "
                             "ORDER BY rowid").fetchall()
    # Bases first: every member lookup through inheritance needs them.
    for path, caller, rel, kind, scope, head, rest, attr, line in references:
        if rel == "inherits" and caller in resolver.symbols:
            target = resolver.reference(path, kind, scope, head, rest, attr)
            if target and target[0] == "symbol" and resolver.symbols[target[1]][3] == "class" and target[1] != caller:
                resolver.bases.setdefault(caller, []).append(target)
                edges.add(caller, rel, target[1], path, resolver.symbols[target[1]][0], line, target[2], target[3])
    for path, caller, rel, kind, scope, head, rest, attr, line in references:
        if rel == "inherits":
            continue
        target = resolver.reference(path, kind, scope, head, rest, attr)
        if not target or target[0] != "symbol" or target[1] == caller:
            continue
        confidence, tier = target[2], target[3]
        if rel == "indirect":
            if resolver.symbols[target[1]][3] not in ("function", "method", "class"):
                continue
            confidence, tier = min(confidence, INDIRECT_CONFIDENCE), INFERRED
        edges.add(caller, rel, target[1], path, resolver.symbols[target[1]][0], line, confidence, tier)
    rows = edges.rows()
    con.execute("DELETE FROM code_edge")
    con.executemany("INSERT INTO code_edge(src, rel, dst, src_path, dst_path, line, confidence, tier, deferred, sites, "
                    "lines) VALUES (?,?,?,?,?,?,?,?,?,?,?)", rows)
    return len(rows)


def import_edges(resolver, edges, row):
    """File-to-file `imports` edges, plus a `uses` edge from the importing file to each imported
    symbol (`from m import name`), so impact of that symbol finds the file."""
    path, alias, module, name, level, line, deferred, _, style, export = row
    if style == "py":
        source = resolver.python_module(path, module, level) if module or level else None
        target_file, symbol = source, None
        if alias != "*" and name:
            found = resolver.export(source, name) if source else None
            if found is None or found[0] == "module":
                submodule = resolver.python_module(path, (module + "." if module else "") + name, level)
                target_file = submodule or target_file
            if found and found[0] == "symbol":
                symbol = found
        if target_file and target_file != path:
            edges.add("file:" + path, "imports", "file:" + target_file, path, target_file, line, 1.0, OBSERVED, deferred)
        if symbol and resolver.symbols[symbol[1]][0] != path:
            edges.add("file:" + path, "uses", symbol[1], path, resolver.symbols[symbol[1]][0], line, symbol[2], symbol[3],
                      deferred)
        return
    if style == "js":
        if module is None:
            return
        target_file = resolver.script(path, module)
        if target_file and target_file != path:
            edges.add("file:" + path, "imports", "file:" + target_file, path, target_file, line, 1.0, OBSERVED, deferred)
        if target_file and name not in (None, "*") and not export:
            found = resolver.export(target_file, name)
            if found and found[0] == "symbol" and resolver.symbols[found[1]][0] != path:
                edges.add("file:" + path, "uses", found[1], path, resolver.symbols[found[1]][0], line, found[2], found[3],
                          deferred)
        return
    for target_file in resolver.languages.targets(style, path, module, name):
        if target_file != path:
            edges.add("file:" + path, "imports", "file:" + target_file, path, target_file, line, 1.0, OBSERVED, deferred)


