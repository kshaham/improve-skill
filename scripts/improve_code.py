"""Code structure of the repository, kept beside the knowledge graph. Standard library only.

The knowledge graph remembers work (tasks, outcomes, knowledge). This module adds what the
code itself says, the way Graphify's AST pass does, but with the standard library: Python is
parsed with `ast`; JavaScript/TypeScript, Go, Java/Kotlin, Ruby, and C/C++ are read with
conservative regular expressions (improve_code_lang.py). It lives in its own tables of
`graph.db`, so it never competes with knowledge for the graph's size bounds and can be
rebuilt at any time:

  code_file    path, content sha256, size, mtime, language, module, parse error, last-good flag
  code_symbol  path::qualname, name, kind (module, class, function, method), lines, docstring
  code_import  per file and scope: alias -> module (and imported name), with the line
  code_call    per file: references (calls, bases, decorators, annotations, callbacks, fixtures)
               with how the head name is bound where it is used
  code_attr    per class: attribute -> the class assigned to it (`self.client = Client()`)
  code_note    `# WHY:` / `# NOTE:` / `# HACK:` / ... comments (secrets redacted)
  code_edge    resolved: imports, calls, inherits, uses, indirect; every site counted

Change detection is Graphify's racily-clean stat check: a (size, mtime) match is trusted only
when the file was indexed at least two seconds after it was last modified; otherwise the
content hash decides. A newer extractor (`CODE_VERSION`) re-reads every file once. A file that
stops parsing keeps its last good facts (marked stale) until it parses again.

Resolution refuses to guess. Python's own binding rules decide what a name means where it is
used: a parameter, a local assignment, a loop or `with` target, a nested definition, or an
import (even of a third-party module) shadows anything else, and a builtin never resolves to a
repository symbol. A reference through an import, a definition in the same module, `self`,
`super()`, or an instance whose class is known is *observed* (1.0). A name bound nowhere in its
module and defined exactly once in the repository is *inferred* (0.85; 0.75 when only tests or
only non-tests are kept to make it unique; 0.6 for a test helper picked by path proximity).
A callable passed as an argument is an `indirect` edge (inferred, at most 0.6).
"""

