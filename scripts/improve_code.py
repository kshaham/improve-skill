def leaf_types():
    """AST node types that can hold no reference or binding: the walk stops at them at once
    (half of a module's nodes are names, constants, contexts, and operators)."""
    found = {"Name", "Constant", "Pass", "Break", "Continue", "alias", "Num", "Str", "Bytes", "NameConstant", "Ellipsis"}
    pending = [ast.expr_context, ast.operator, ast.boolop, ast.cmpop, ast.unaryop]
    while pending:
        cls = pending.pop()
        found.add(cls.__name__)
        pending.extend(cls.__subclasses__())
    return frozenset(found)


