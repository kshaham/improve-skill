def redact(text):
    for pattern in SECRETS:
        text = pattern.sub("[redacted]", text)
    return text


def is_test(path):
    """Graphify's segment-aware rule: a test directory segment or a test file name, never a
    substring (`src/contest.py` and `latest_test_data/x.py` are not tests)."""
    parts = path.replace("\\", "/").split("/")
    return any(part.lower() in TEST_DIRECTORIES for part in parts[:-1]) or bool(TEST_FILE.match(parts[-1]))


def language(path):
    """The language name of a file the code layer reads, or None."""
    if path.endswith(PYTHON):
        return "python"
    return lang_module.language_of(path)


def vendored(path):
    parts = path.split("/")
    return any(part in VENDORED_DIRECTORIES for part in parts[:-1]) or path.endswith(MINIFIED)


def generated(path, text):
    """Generated code is kept as an import target only: its calls and symbols are noise."""
    head = text[:4000]
    if GENERATED_MARKER.search(head) or posixpath.basename(path).endswith(GENERATED_NAMES):
        return True
    if path.endswith(".py"):
        if re.search(r"^(?:down_)?revision\s*[:=]", head, re.M) and "down_revision" in head and "def upgrade(" in text:
            return True
        if "/migrations/" in "/" + path and "class Migration(migrations.Migration)" in text:
            return True
    return False


