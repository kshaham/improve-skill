def ensure_schema(con):
    """Create the code tables, statement by statement: `executescript` would commit the caller's
    open transaction, and the code layer is written inside the graph's session. A table whose
    columns differ from this version's drops every code table: the layer is rebuilt from the
    working tree, and mixing old facts with new ones would resolve wrongly."""
    outdated = False
    for table, columns in TABLES.items():
        wanted = [column.split()[0] for column in columns.split(", ")]
        existing = [row[1] for row in con.execute(f"PRAGMA table_info({table})")]
        if existing and existing != wanted:
            outdated = True
    if outdated:
        for table in TABLES:
            con.execute(f"DROP TABLE IF EXISTS {table}")
    for table, columns in TABLES.items():
        con.execute(f"CREATE TABLE IF NOT EXISTS {table}({columns})")
    for statement in INDEXES:
        con.execute(statement)


def available(con):
    """True when this version's code tables exist. An index written by an older version (no
    `code_meta`) reads as absent until the next sync rebuilds it, instead of failing a query."""
    tables = {row[0] for row in con.execute("SELECT name FROM sqlite_master WHERE type='table'")}
    return {"code_file", "code_symbol", "code_edge", "code_meta"} <= tables


def meta_get(con, key, default=None):
    try:
        row = con.execute("SELECT value FROM code_meta WHERE key=?", (key,)).fetchone()
    except Exception:  # noqa: BLE001 - an index written before code_meta existed has no metadata.
        return default
    return row[0] if row else default


def meta_set(con, key, value):
    """Write only a changed value: an unchanged sync should leave no dirty pages behind."""
    if meta_get(con, key) != value:
        con.execute("INSERT OR REPLACE INTO code_meta(key, value) VALUES (?, ?)", (key, value))


# ---------------------------------------------------------------- module names

def module_name(path):
    """`pkg/mod.py` -> `pkg.mod`; `pkg/__init__.py` -> `pkg`."""
    stem = path.rsplit(".", 1)[0]
    parts = stem.split("/")
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def package_directories(paths):
    return {posixpath.dirname(path) for path in paths if posixpath.basename(path) in ("__init__.py", "__init__.pyi")}


def module_aliases(path, packages=None):
    """Names an absolute import may use for this file. Every ancestor directory above the file's
    outermost package (a directory without `__init__.py`) can be on `sys.path`, so each one is a
    candidate root: `backend/app/models.py` is `app.models` or `backend.app.models`. Ambiguous
    names are refused by the resolver, not here. Without `packages` (directories holding an
    `__init__.py`), only the full dotted path and the conventional source roots are known."""
    if packages is None:
        names = [module_name(path)]
        names.extend(module_name(path[len(root):]) for root in SOURCE_ROOTS if path.startswith(root))
        return [name for name in names if name]
    parts = module_name(path).split(".")
    directories = posixpath.dirname(path).split("/") if posixpath.dirname(path) else []
    top = len(directories)
    while top > 0 and "/".join(directories[:top]) in packages:
        top -= 1
    names = [".".join(parts[root:]) for root in range(top, -1, -1)]
    return [name for name in dict.fromkeys(names) if name]


# ---------------------------------------------------------------- Python extraction

class Scope:
    """One Python namespace and every way its names are bound (flow-insensitive, as Python's own
    compiler decides locality: a name assigned anywhere in a function is local throughout)."""

    __slots__ = ("kind", "key", "parent", "names", "globals", "nonlocals")

    def __init__(self, kind, key, parent):
        self.kind = kind  # module, class, function, lambda, comprehension
        self.key = key  # qualname of the def/class that opened it ("" for the module)
        self.parent = parent
        self.names = {}
        self.globals = set()
        self.nonlocals = set()


def dotted_parts(node):
    """(`a`, `b`, `c`) for a Name/Attribute chain, else None (calls on call results are not followed)."""
    parts = []
    while isinstance(node, ast.Attribute):
        parts.append(node.attr)
        node = node.value
    if isinstance(node, ast.Name):
        parts.append(node.id)
        return tuple(reversed(parts))
    return None


def dotted(node):
    parts = dotted_parts(node)
    return ".".join(parts) if parts else None


def string_expression(node):
    """The expression inside a string annotation (`"Client"`), or None."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str) and len(node.value) < 300:
        try:
            return ast.parse(node.value.strip(), mode="eval").body
        except (SyntaxError, ValueError):
            return None
    return None


def type_parts(annotation):
    """The class an annotation names when it names exactly one (`Client`, `"Client"`, `m.Client`)."""
    if annotation is None:
        return None
    parts = dotted_parts(annotation)
    if parts:
        return parts
    inner = string_expression(annotation)
    return dotted_parts(inner) if inner is not None else None


def constructor_parts(value):
    return dotted_parts(value.func) if isinstance(value, ast.Call) else None


def annotation_references(node):
    """Every dotted name an annotation mentions (`Optional[m.Client]` -> Optional, m.Client)."""
    parts = dotted_parts(node)
    if parts:
        return [parts]
    inner = string_expression(node)
    if inner is not None:
        return annotation_references(inner)
    found = []
    for child in ast.iter_child_nodes(node):
        found.extend(annotation_references(child))
    return found


class PythonFacts:
    """One pass over a module: symbols, imports with the scope that binds them, and every
    reference (call, base class, decorator, annotation, isinstance/except class, callable passed as
    an argument, pytest fixture parameter) with the scope it was made in. Python's binding rules
    are applied afterwards (`references`), once every scope's names are known."""

    def __init__(self, path):
        self.path = path
        self.module = Scope("module", "", None)
        self.symbols = [(f"{path}::", "", "", "module", 1, None, None, None, None)]
        self.imports = []
        self.refs = []
        self.attributes = {}
        self.exports = None
        self.guarded = 0
        self.fixture_file = is_test(path)
        self.handlers = {"FunctionDef": self.visit_function, "AsyncFunctionDef": self.visit_function,
                         "ClassDef": self.visit_class, "Lambda": self.visit_lambda, "Import": self.visit_import,
                         "ImportFrom": self.visit_import_from, "Global": self.visit_global,
                         "Nonlocal": self.visit_nonlocal, "Assign": self.visit_assign,
                         "AnnAssign": self.visit_ann_assign, "AugAssign": self.visit_aug_assign,
                         "For": self.visit_for, "AsyncFor": self.visit_for, "With": self.visit_with,
                         "AsyncWith": self.visit_with, "NamedExpr": self.visit_named, "ExceptHandler": self.visit_except,
                         "Delete": self.visit_delete, "If": self.visit_if, "Call": self.visit_call,
                         "MatchAs": self.visit_match_name, "MatchStar": self.visit_match_name,
                         "MatchMapping": self.visit_match_mapping, "MatchClass": self.visit_match_class}
        for name in COMPREHENSIONS:
            self.handlers[name] = self.visit_comprehension

    # ---- traversal

    def visit(self, node, scope, caller):
        name = type(node).__name__
        if name in LEAVES:
            return
        handler = self.handlers.get(name)
        if handler:
            handler(node, scope, caller)
            return
        for field in node._fields:
            value = getattr(node, field, None)
            if isinstance(value, list):
                for item in value:
                    if isinstance(item, ast.AST):
                        self.visit(item, scope, caller)
            elif isinstance(value, ast.AST):
                self.visit(value, scope, caller)

    def visit_body(self, statements, scope, caller):
        for statement in statements:
            self.visit(statement, scope, caller)

    def bind(self, scope, name, binding):
        """Bind a name where Python would: `global` sends it to the module, `nonlocal` to the
        nearest enclosing function."""
        target = scope
        if name in scope.globals:
            target = self.module
        elif name in scope.nonlocals:
            outer = scope.parent
            while outer is not None and outer.kind == "class":
                outer = outer.parent
            target = outer or scope
        target.names.setdefault(name, []).append(binding)
        return target

    def qualify(self, scope, name):
        return f"{scope.key}.{name}" if scope.key else name

    def deferred(self, scope):
        """An import inside a function or a TYPE_CHECKING block does not bind at import time."""
        current = scope
        while current is not None:
            if current.kind in ("function", "lambda"):
                return 1
            current = current.parent
        return int(self.guarded > 0)

    def reference(self, scope, caller, rel, expression, line):
        self.refs.append((scope, caller, rel, expression, line))

    # ---- definitions

    def define(self, node, kind, qualname, scope, flags):
        doc = ast.get_docstring(node, clean=True)
        doc = redact(doc.strip().splitlines()[0][:200]) if doc and doc.strip() else None
        parent = f"{self.path}::{scope.key}" if scope.key else None
        start = min([node.lineno] + [decorator.lineno for decorator in node.decorator_list])
        self.symbols.append((f"{self.path}::{qualname}", node.name, qualname, kind, start,
                             getattr(node, "end_lineno", None), parent, doc, flags))

    def visit_function(self, node, scope, caller):
        in_class = scope.kind == "class"
        qualname = self.qualify(scope, node.name)
        symbol = f"{self.path}::{qualname}"
        names = [dotted_parts(item.func if isinstance(item, ast.Call) else item) for item in node.decorator_list]
        fixture = any(parts and parts[-1] == "fixture" for parts in names)
        static = any(parts == ("staticmethod",) for parts in names)
        self.define(node, "method" if in_class else "function", qualname, scope, "fixture" if fixture else None)
        self.bind(scope, node.name, ("def", qualname))
        self.decorate(node, scope, caller, symbol)
        for default in list(node.args.defaults) + [item for item in node.args.kw_defaults if item is not None]:
            self.visit(default, scope, caller)
        inner = Scope("function", qualname, scope)
        wants_fixtures = self.fixture_file and (fixture or node.name.startswith("test"))
        self.bind_parameters(node.args, inner, scope, symbol, in_class and not static, wants_fixtures)
        if node.returns is not None:
            self.annotation(node.returns, scope, symbol)
        self.visit_body(node.body, inner, symbol)

    def bind_parameters(self, arguments, inner, outer, symbol, method, wants_fixtures):
        positional = list(getattr(arguments, "posonlyargs", [])) + list(arguments.args)
        extra = [item for item in (arguments.vararg, arguments.kwarg) if item is not None]
        for index, argument in enumerate(positional + list(arguments.kwonlyargs) + extra):
            if argument.annotation is not None:
                self.annotation(argument.annotation, outer, symbol)
            if method and index == 0 and positional:
                inner.names.setdefault(argument.arg, []).append(("self", outer.key))
                continue
            parts = type_parts(argument.annotation)
            inner.names.setdefault(argument.arg, []).append(("type", parts, outer) if parts else ASSIGNED)
            if wants_fixtures and argument not in extra:
                self.reference(inner, symbol, "uses", ("fixture", argument.arg), argument.lineno)

    def visit_class(self, node, scope, caller):
        qualname = self.qualify(scope, node.name)
        symbol = f"{self.path}::{qualname}"
        self.define(node, "class", qualname, scope, None)
        self.bind(scope, node.name, ("def", qualname))
        for base in node.bases:
            parts = dotted_parts(base.value if isinstance(base, ast.Subscript) else base)
            if parts:
                self.reference(scope, symbol, "inherits", ("dotted", parts), base.lineno)
                if isinstance(base, ast.Subscript):
                    self.visit(base.slice, scope, symbol)
            else:
                self.visit(base, scope, caller)
        for keyword in node.keywords:
            parts = dotted_parts(keyword.value)
            if parts:
                self.reference(scope, symbol, "uses", ("dotted", parts), keyword.value.lineno)
            else:
                self.visit(keyword.value, scope, caller)
        self.decorate(node, scope, caller, symbol)
        self.visit_body(node.body, Scope("class", qualname, scope), symbol)

    def decorate(self, node, scope, caller, symbol):
        """A decorator is used by the definition it decorates (impact of a decorator finds its users)."""
        for decorator in node.decorator_list:
            target = decorator.func if isinstance(decorator, ast.Call) else decorator
            parts = dotted_parts(target)
            if parts:
                self.reference(scope, symbol, "uses", ("dotted", parts), decorator.lineno)
            else:
                self.visit(target, scope, caller)
            if isinstance(decorator, ast.Call):
                for argument in list(decorator.args) + [keyword.value for keyword in decorator.keywords]:
                    self.argument(argument, scope, caller)

    def visit_lambda(self, node, scope, caller):
        for default in list(node.args.defaults) + [item for item in node.args.kw_defaults if item is not None]:
            self.visit(default, scope, caller)
        inner = Scope("lambda", scope.key, scope)
        arguments = node.args
        for argument in (list(getattr(arguments, "posonlyargs", [])) + list(arguments.args) + list(arguments.kwonlyargs)
                         + [item for item in (arguments.vararg, arguments.kwarg) if item is not None]):
            inner.names.setdefault(argument.arg, []).append(ASSIGNED)
        self.visit(node.body, inner, caller)

    def visit_comprehension(self, node, scope, caller):
        inner = Scope("comprehension", scope.key, scope)
        for index, generator in enumerate(node.generators):
            self.visit(generator.iter, scope if index == 0 else inner, caller)
            self.assign(generator.target, inner, caller, None)
            for condition in generator.ifs:
                self.visit(condition, inner, caller)
        for part in ("elt", "key", "value"):
            if getattr(node, part, None) is not None:
                self.visit(getattr(node, part), inner, caller)

    # ---- imports and declarations

    def visit_import(self, node, scope, caller):
        deferred = self.deferred(scope)
        for alias in node.names:
            bound = alias.asname or alias.name.split(".")[0]  # `import a.b` binds `a`.
            target = self.bind(scope, bound, IMPORTED)
            self.imports.append((bound, alias.name, None, 0, node.lineno, deferred, target.key, "py", 0))

    def visit_import_from(self, node, scope, caller):
        deferred = self.deferred(scope)
        for alias in node.names:
            if alias.name == "*":
                self.imports.append(("*", node.module or "", None, node.level, node.lineno, deferred, scope.key, "py", 0))
                continue
            bound = alias.asname or alias.name
            target = self.bind(scope, bound, IMPORTED)
            self.imports.append((bound, node.module or "", alias.name, node.level, node.lineno, deferred, target.key,
                                 "py", 0))

    def visit_global(self, node, scope, caller):
        scope.globals.update(node.names)

    def visit_nonlocal(self, node, scope, caller):
        scope.nonlocals.update(node.names)

    def visit_if(self, node, scope, caller):
        test = dotted(node.test) or ""
        if test.split(".")[-1] != "TYPE_CHECKING":
            for child in ast.iter_child_nodes(node):
                self.visit(child, scope, caller)
            return
        self.visit(node.test, scope, caller)
        self.guarded += 1
        self.visit_body(node.body, scope, caller)
        self.guarded -= 1
        self.visit_body(node.orelse, scope, caller)

    # ---- bindings

    def assign(self, target, scope, caller, parts):
        """Bind an assignment target; `parts` is the class constructed into it, if any."""
        if isinstance(target, ast.Name):
            self.bind(scope, target.id, ("type", parts, scope) if parts else ASSIGNED)
            if scope.kind == "class":
                self.attributes.setdefault((scope.key, target.id), []).append((parts, scope) if parts else None)
        elif isinstance(target, (ast.Tuple, ast.List)):
            for element in target.elts:
                self.assign(element, scope, caller, None)
        elif isinstance(target, ast.Starred):
            self.assign(target.value, scope, caller, None)
        elif isinstance(target, ast.Attribute):
            self.attribute_type(target, scope, parts)
            self.visit(target.value, scope, caller)
        else:
            self.visit(target, scope, caller)

    def attribute_type(self, target, scope, parts):
        """`self.attr = Cls()` in a method records the class of the attribute; any other value
        assigned to the same attribute anywhere in the class makes it unknown."""
        if not isinstance(target.value, ast.Name) or scope.kind != "function":
            return
        bindings = scope.names.get(target.value.id, [])
        owners = {binding[1] for binding in bindings if binding[0] == "self"}
        if len(owners) == 1 and len(bindings) == 1:
            self.attributes.setdefault((owners.pop(), target.attr), []).append((parts, scope) if parts else None)

    def visit_assign(self, node, scope, caller):
        parts = constructor_parts(node.value)
        for target in node.targets:
            self.assign(target, scope, caller, parts)
            if scope is self.module and isinstance(target, ast.Name) and target.id == "__all__":
                self.read_all(node.value, extend=False)
        self.visit(node.value, scope, caller)

    def visit_ann_assign(self, node, scope, caller):
        self.annotation(node.annotation, scope, caller)
        parts = type_parts(node.annotation) or (constructor_parts(node.value) if node.value is not None else None)
        self.assign(node.target, scope, caller, parts)
        if node.value is not None:
            self.visit(node.value, scope, caller)

    def visit_aug_assign(self, node, scope, caller):
        self.assign(node.target, scope, caller, None)
        if scope is self.module and isinstance(node.target, ast.Name) and node.target.id == "__all__":
            self.read_all(node.value, extend=True)
        self.visit(node.value, scope, caller)

    def read_all(self, value, extend):
        names = None
        if isinstance(value, (ast.List, ast.Tuple)) and all(
                isinstance(item, ast.Constant) and isinstance(item.value, str) for item in value.elts):
            names = [item.value for item in value.elts]
        if names is None or self.exports == "dynamic":
            self.exports = "dynamic"
        else:
            self.exports = (list(self.exports or []) if extend else []) + names

    def visit_for(self, node, scope, caller):
        self.assign(node.target, scope, caller, None)
        self.visit(node.iter, scope, caller)
        self.visit_body(node.body, scope, caller)
        self.visit_body(node.orelse, scope, caller)

    def visit_with(self, node, scope, caller):
        for item in node.items:
            if item.optional_vars is not None:
                parts = constructor_parts(item.context_expr) if isinstance(item.optional_vars, ast.Name) else None
                self.assign(item.optional_vars, scope, caller, parts)
            self.visit(item.context_expr, scope, caller)
        self.visit_body(node.body, scope, caller)

    def visit_named(self, node, scope, caller):
        owner = scope
        while owner.kind == "comprehension" and owner.parent is not None:
            owner = owner.parent  # A walrus in a comprehension binds in the enclosing function.
        if isinstance(node.target, ast.Name):
            self.bind(owner, node.target.id, ASSIGNED)
        self.visit(node.value, scope, caller)

    def visit_except(self, node, scope, caller):
        if node.type is not None:
            self.class_arguments(node.type, scope, caller)
        if node.name:
            self.bind(scope, node.name, ASSIGNED)
        self.visit_body(node.body, scope, caller)

    def visit_delete(self, node, scope, caller):
        for target in node.targets:
            if isinstance(target, ast.Name):
                self.bind(scope, target.id, ASSIGNED)
            else:
                self.visit(target, scope, caller)

    def visit_match_name(self, node, scope, caller):
        if getattr(node, "name", None):
            self.bind(scope, node.name, ASSIGNED)
        for child in ast.iter_child_nodes(node):
            self.visit(child, scope, caller)

    def visit_match_mapping(self, node, scope, caller):
        if getattr(node, "rest", None):
            self.bind(scope, node.rest, ASSIGNED)
        for child in ast.iter_child_nodes(node):
            self.visit(child, scope, caller)

    def visit_match_class(self, node, scope, caller):
        parts = dotted_parts(node.cls)
        if parts:
            self.reference(scope, caller, "uses", ("dotted", parts), node.cls.lineno)
        for child in list(node.patterns) + list(node.kwd_patterns):
            self.visit(child, scope, caller)

    # ---- references

    def annotation(self, node, scope, caller):
        for parts in annotation_references(node):
            self.reference(scope, caller, "uses", ("dotted", parts), getattr(node, "lineno", 1))

    def class_arguments(self, node, scope, caller):
        """`except (A, m.B)` / `isinstance(x, (A, B))`: each class is used."""
        items = node.elts if isinstance(node, ast.Tuple) else [node]
        for item in items:
            parts = dotted_parts(item)
            if parts:
                self.reference(scope, caller, "uses", ("dotted", parts), item.lineno)
            else:
                self.visit(item, scope, caller)

    def argument(self, value, scope, caller):
        parts = dotted_parts(value)
        if parts:
            self.reference(scope, caller, "indirect", ("dotted", parts), value.lineno)
        else:
            self.visit(value, scope, caller)

    def visit_call(self, node, scope, caller):
        function = node.func
        parts = dotted_parts(function)
        if parts:
            self.reference(scope, caller, "calls", ("dotted", parts), node.lineno)
        elif isinstance(function, ast.Attribute) and isinstance(function.value, ast.Call):
            inner = function.value
            if isinstance(inner.func, ast.Name) and inner.func.id == "super":
                self.reference(scope, caller, "calls", ("super", function.attr), node.lineno)
            else:
                made = dotted_parts(inner.func)
                if made:  # `Client().send()`
                    self.reference(scope, caller, "calls", ("instance", made, function.attr), node.lineno)
            self.visit(inner, scope, caller)
        else:
            self.visit(function, scope, caller)
        checks_class = parts in (("isinstance",), ("issubclass",))
        for index, argument in enumerate(node.args):
            if checks_class and index == 1:
                self.class_arguments(argument, scope, caller)
            elif isinstance(argument, ast.Starred):
                self.visit(argument.value, scope, caller)
            else:
                self.argument(argument, scope, caller)
        for keyword in node.keywords:
            self.argument(keyword.value, scope, caller)

    # ---- applying Python's binding rules

    def lookup(self, scope, name):
        """(scope that binds the name, its bindings), or (None, None) when the module never binds
        it. Class bodies are visible only to code directly inside them."""
        current, direct = scope, True
        while current is not None:
            if name in current.globals:
                current = self.module
            if current.kind != "class" or direct:
                if name in current.names:
                    return current, current.names[name]
            direct = False
            current = current.parent
        return None, None

    def classify(self, scope, name):
        """How a name is bound where it is used: ("def", ""), ("nested", qualname), ("import",
        scope key), ("type", class parts, scope), ("self", class qualname), FREE, or None when it
        is a builtin, a plain local, or bound more than one way (never guessed)."""
        found, bindings = self.lookup(scope, name)
        if found is None:
            return None if name in BUILTIN_NAMES else FREE
        kinds = {binding[0] for binding in bindings}
        if len(kinds) != 1:
            return None
        kind = kinds.pop()
        if kind == "def":
            qualnames = {binding[1] for binding in bindings}
            if len(qualnames) != 1:
                return None
            return ("def", "") if found is self.module else ("nested", qualnames.pop())
        if kind == "import":
            return ("import", found.key)
        if kind == "type":
            if len({binding[1] for binding in bindings}) != 1:
                return None
            return bindings[0]
        if kind == "self":
            owners = {binding[1] for binding in bindings}
            return ("self", owners.pop()) if len(owners) == 1 else None
        return None

    def class_row(self, scope, parts):
        """How a class expression resolves: (kind, scope key, head, rest), or None."""
        head = self.classify(scope, parts[0])
        if head is None or head[0] not in ("def", "nested", "import", "free"):
            return None
        rest = ".".join(parts[1:]) or None
        name = head[1] if head[0] == "nested" else parts[0]
        return (head[0], head[1] if head[0] == "import" else "", name, rest)

    def method_owner(self, scope):
        current = scope
        while current is not None and current.kind in ("lambda", "comprehension"):
            current = current.parent
        if current is not None and current.kind == "function" and current.parent is not None \
                and current.parent.kind == "class":
            return current.parent.key
        return None

    def reference_row(self, scope, expression):
        """(kind, scope key, head, rest, attr) for one reference, or None when it cannot be linked."""
        form = expression[0]
        if form == "fixture":
            return ("fixture", "", expression[1], None, None)
        if form == "super":
            if self.lookup(scope, "super")[0] is not None:
                return None
            owner = self.method_owner(scope)
            return ("super", "", owner, None, expression[1]) if owner else None
        if form == "instance":
            made = self.class_row(scope, expression[1])
            return (*made, expression[2]) if made else None
        parts = expression[1]
        head = self.classify(scope, parts[0])
        if head is None:
            return None
        kind = head[0]
        if kind in ("def", "import", "free"):
            return (kind, head[1], parts[0], ".".join(parts[1:]) or None, None)
        if kind == "nested":
            return ("nested", "", head[1], ".".join(parts[1:]) or None, None)
        if kind == "type":
            if len(parts) != 2:
                return None  # Calling the instance itself, or a chain past one attribute.
            made = self.class_row(head[2], head[1])
            return (*made, parts[1]) if made else None
        owner = head[1]
        if len(parts) == 1:
            return ("self", "", owner, None, None)
        if len(parts) == 2:
            return ("self", "", owner, None, parts[1])
        if len(parts) == 3:
            return ("selfattr", "", owner, parts[1], parts[2])
        return None

    def references(self):
        rows = []
        for scope, caller, rel, expression, line in self.refs:
            row = self.reference_row(scope, expression)
            if row:
                rows.append((caller, rel, *row, line))
        return rows

    def attribute_rows(self):
        rows = []
        for (owner, attribute), values in sorted(self.attributes.items(), key=lambda item: item[0]):
            typed = {value[0] for value in values if value}
            made = None
            if len(typed) == 1 and all(values):
                made = self.class_row(values[0][1], values[0][0])
            rows.append((owner, attribute, *(made or (None, None, None, None))))
        return rows


def extract_python(path, source):
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")  # Invalid escapes in the source are its own business.
        tree = ast.parse(source, filename=path)
    facts = PythonFacts(path)
    facts.visit_body(tree.body, facts.module, f"{path}::")
    return {"symbols": facts.symbols, "imports": facts.imports, "calls": facts.references(),
            "attributes": facts.attribute_rows(), "notes": python_notes(source), "exports": facts.exports}


def python_notes(source):
    if not NOTE_WORDS.search(source):
        return []
    notes = []
    with contextlib.suppress(tokenize.TokenError, IndentationError, SyntaxError):
        for token in tokenize.generate_tokens(io.StringIO(source).readline):
            if token.type == tokenize.COMMENT:
                match = NOTE_PATTERN.match(token.string)
                if match:
                    notes.append((token.start[0], match.group(1), match.group(2)))
    return notes


def extract(path, lang, source):
    """Facts for one file, by language; raises on a file that does not parse."""
    if generated(path, source):
        return {"symbols": [(f"{path}::", "", "", "module", 1, None, None, None, None)], "imports": [], "calls": [],
                "attributes": [], "notes": [], "exports": None, "generated": True}
    if lang == "python":
        facts = extract_python(path, source)
    elif lang in ("javascript", "typescript"):
        facts = lang_module.extract_script(path, source, NOTE_PATTERN)
    else:
        facts = lang_module.extract_other(lang, path, source, NOTE_PATTERN)
    facts.setdefault("attributes", [])
    facts.setdefault("exports", None)
    return facts


# ---------------------------------------------------------------- indexing

def git_lines(repo, *args, timeout=30):
    try:
        output = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, timeout=timeout, check=True).stdout
    except (OSError, subprocess.SubprocessError):
        return None
    return output.decode(errors="replace")


def list_tracked(repo):
    """Every tracked path (outside `.improve/`), or None when this is not a git repository."""
    output = git_lines(repo, "ls-files", "-z")
    if output is None:
        return None
    return sorted(path for path in output.split("\0") if path and not path.startswith(".improve/"))


def tracked(repo):
    """Tracked files the code layer can read (vendored and minified code left out)."""
    listing = list_tracked(repo)
    if listing is None:
        return None
    return [path for path in listing if language(path) and not vendored(path)]


def git_head(repo):
    output = git_lines(repo, "rev-parse", "--verify", "-q", "HEAD", timeout=10)
    return output.strip() or None if output else None


def listing_and_head(repo):
    """`git ls-files` and `git rev-parse HEAD`, run concurrently: on a busy machine each git
    start costs more than reading an unchanged index."""
    try:
        head_process = subprocess.Popen(["git", "-C", str(repo), "rev-parse", "--verify", "-q", "HEAD"],
                                        stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
    except OSError:
        return list_tracked(repo), None
    listing = None
    try:
        listing = list_tracked(repo)
        output, _ = head_process.communicate(timeout=30)
    except subprocess.SubprocessError:
        head_process.kill()
        head_process.communicate()
        return listing, None
    head = output.decode(errors="replace").strip() if head_process.returncode == 0 else ""
    return listing, head or None


def plan_files(listing):
    """Split a listing into files to index (with their language), unsupported languages, and vendored code."""
    plan = {"index": [], "unsupported": {}, "vendored": 0}
    for path in listing:
        lang = language(path)
        if lang is None:
            other = UNSUPPORTED.get(posixpath.splitext(path)[1].lower())
            if other:
                plan["unsupported"][other] = plan["unsupported"].get(other, 0) + 1
        elif vendored(path):
            plan["vendored"] += 1
        else:
            plan["index"].append((path, lang))
    return plan


def forget_file(con, path):
    for table in FACT_TABLES:
        con.execute(f"DELETE FROM {table} WHERE path=?", (path,))
    con.execute("DELETE FROM code_file WHERE path=?", (path,))


def store_facts(con, path, lang, facts, record):
    """Replace one file's facts. `record` is (sha, size, mtime_ns, indexed_ns, error)."""
    forget_file(con, path)
    module = facts.get("module")
    exports = facts.get("exports")
    con.execute("INSERT INTO code_file(path, sha, size, mtime_ns, indexed_ns, lang, module, version, error, stale_parse, "
                "generated, exports) VALUES (?,?,?,?,?,?,?,?,?,0,?,?)",
                (path, *record[:4], lang, module if module is not None else module_name(path), CODE_VERSION, record[4],
                 int(bool(facts.get("generated"))), json.dumps(exports) if exports is not None else None))
    con.executemany("INSERT OR REPLACE INTO code_symbol(id, path, name, qualname, kind, line, end_line, parent, doc, flags) "
                    "VALUES (?,?,?,?,?,?,?,?,?,?)", [(row[0], path, *row[1:]) for row in facts["symbols"]])
    con.executemany("INSERT INTO code_import(path, alias, module, name, level, line, deferred, scope, style, export) "
                    "VALUES (?,?,?,?,?,?,?,?,?,?)", [(path, *row) for row in facts["imports"]])
    con.executemany("INSERT INTO code_call(path, caller, rel, kind, scope, head, rest, attr, line) "
                    "VALUES (?,?,?,?,?,?,?,?,?)", [(path, *row) for row in facts["calls"]])
    con.executemany("INSERT INTO code_attr(path, owner, attr, kind, scope, head, rest) VALUES (?,?,?,?,?,?,?)",
                    [(path, *row) for row in facts["attributes"]])
    con.executemany("INSERT INTO code_note(path, line, tag, text) VALUES (?,?,?,?)",
                    [(path, line, tag, redact(text)[:MAX_NOTE]) for line, tag, text in facts["notes"][:MAX_NOTES_PER_FILE]])


def shrink_reason(con, known, wanted, head, force):
    """Graphify's shrink guard: when `git ls-files` suddenly lists under half of what is indexed
    and HEAD has not moved, something is wrong with the listing (a broken index, a sparse
    checkout); pruning would throw away most of the code layer."""
    if force or head is None or len(known) < SHRINK_MIN_FILES or len(wanted) * 2 >= len(known):
        return None
    if meta_get(con, "head") != head:
        return None
    return (f"git ls-files lists {len(wanted)} readable files but {len(known)} are indexed and HEAD is unchanged; "
            "kept the index instead of pruning it (commit the deletions, or run `code index --force`)")


def index(con, repo, max_seconds=DEFAULT_SECONDS, paths=None, force=False):
    """Bring the code tables up to date with the working tree. Incremental and time-bounded:
    files left over when the budget runs out are read on the next call. Runs inside the
    caller's write transaction."""
    started = time.monotonic()
    ensure_schema(con)
    repo = Path(repo)
    listing, head = (paths, None) if paths is not None else listing_and_head(repo)
    report = {"files": 0, "parsed": 0, "unchanged": 0, "removed": 0, "errors": 0, "skipped": 0, "partial": False}
    if listing is None:
        report["error"] = "not a git repository"
        return report
    plan = plan_files(listing)
    current = plan["index"][:MAX_FILES]
    report["files"] = len(current)
    if plan["vendored"]:
        report["vendored"] = plan["vendored"]
    known = {row[0]: row for row in con.execute(
        "SELECT path, sha, size, mtime_ns, indexed_ns, version, error, stale_parse FROM code_file")}
    wanted = {path for path, _ in current}
    refused = shrink_reason(con, known, wanted, head, force) if paths is None else None
    changed = False
    if refused:
        report["shrink_refused"] = refused
    else:
        for path in sorted(set(known) - wanted):
            forget_file(con, path)
            report["removed"] += 1
            changed = True
    stale = []
    for path, lang in current:
        if max_seconds and time.monotonic() - started > max_seconds:
            report["partial"] = True
            break
        outcome = index_file(con, repo, path, lang, known.get(path))
        if outcome in ("parsed", "error", "gone"):
            changed = True
        if outcome in ("error", "stale"):
            report["errors"] += 1
        if outcome == "stale":
            stale.append(path)
        else:
            report[OUTCOME_COUNTER[outcome]] += 1
    if stale:
        report["stale"] = stale
    config = json.dumps(lang_module.load_config(repo, listing), sort_keys=True)
    if meta_get(con, "config", "{}") != config:
        meta_set(con, "config", config)
        changed = True
    if meta_get(con, "resolver") != str(CODE_VERSION):
        changed = True
    count = con.execute("SELECT count(*) FROM code_edge").fetchone()[0]
    report["edges"] = resolve(con) if changed or count == 0 else count
    meta_set(con, "resolver", str(CODE_VERSION))
    meta_set(con, "coverage", json.dumps(coverage_counts(con, plan, len(plan["index"]) - len(current)), sort_keys=True))
    if head and not refused and not report["partial"]:
        meta_set(con, "head", head)  # The commit the whole index reflects (freshness, shrink guard).
    report["symbols"] = con.execute("SELECT count(*) FROM code_symbol WHERE kind != 'module'").fetchone()[0]
    report["seconds"] = round(time.monotonic() - started, 3)
    return report


OUTCOME_COUNTER = {"parsed": "parsed", "error": "parsed", "unchanged": "unchanged", "skipped": "skipped",
                   "gone": "removed"}


def index_file(con, repo, path, lang, row):
    """Bring one file up to date: 'unchanged', 'parsed', 'error' (no earlier facts to keep),
    'stale' (did not parse; the last good facts are kept), 'skipped', or 'gone'."""
    target = repo / path
    try:
        info = target.lstat()
    except OSError:
        if row:
            forget_file(con, path)
            return "gone"
        return "skipped"
    if not target.is_file() or target.is_symlink() or info.st_size > MAX_BYTES:
        if row:
            forget_file(con, path)
        return "skipped"
    if row and row[5] == CODE_VERSION and row[2] == info.st_size and row[3] == info.st_mtime_ns \
            and (row[4] or 0) - info.st_mtime_ns >= RACY_NS:
        return "unchanged"
    try:
        data = target.read_bytes()
    except OSError:
        return "skipped"
    sha = hashlib.sha256(data).hexdigest()
    now = time.time_ns()
    if row and row[5] == CODE_VERSION and row[1] == sha:
        con.execute("UPDATE code_file SET size=?, mtime_ns=?, indexed_ns=? WHERE path=?",
                    (info.st_size, info.st_mtime_ns, now, path))
        return "unchanged"
    try:
        facts = extract(path, lang, data.decode("utf-8"))
        error = None
    except (SyntaxError, ValueError, RecursionError, UnicodeDecodeError, MemoryError) as exc:
        error = f"{type(exc).__name__}: {str(exc)[:160]}"
        if row and row[5] == CODE_VERSION and (row[6] is None or row[7]):
            # Keep the last good parse while the file is mid-edit; say so.
            con.execute("UPDATE code_file SET sha=?, size=?, mtime_ns=?, indexed_ns=?, error=?, stale_parse=1 "
                        "WHERE path=?", (sha, info.st_size, info.st_mtime_ns, now, error, path))
            return "stale"
        facts = {"symbols": [(f"{path}::", "", "", "module", 1, None, None, None, None)], "imports": [], "calls": [],
                 "attributes": [], "notes": []}
    store_facts(con, path, lang, facts, (sha, info.st_size, info.st_mtime_ns, now, error))
    return "error" if error else "parsed"


def coverage_counts(con, plan, over_limit):
    """Per language: tracked files, how many are indexed, failed to parse, kept stale, or are generated."""
    languages = {}
    for _, lang in plan["index"]:
        languages.setdefault(lang, {"tracked": 0, "indexed": 0})["tracked"] += 1
    for lang, error, stale, made in con.execute("SELECT lang, error, stale_parse, generated FROM code_file"):
        row = languages.setdefault(lang, {"tracked": 0, "indexed": 0})
        row["indexed"] += 1
        for key, flag in (("parse_errors", error is not None), ("stale", stale), ("generated", made)):
            if flag:
                row[key] = row.get(key, 0) + 1
    result = {"languages": languages}
    if plan["unsupported"]:
        result["not_indexed"] = plan["unsupported"]
    if plan["vendored"]:
        result["vendored"] = plan["vendored"]
    if over_limit:
        result["over_limit"] = over_limit
    return result


