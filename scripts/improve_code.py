def stats(con):
    if not available(con):
        return {"indexed": False}
    counts = {table: con.execute(f"SELECT count(*) FROM {table}").fetchone()[0]
              for table in ("code_file", "code_symbol", "code_edge", "code_note")}
    tiers = dict(con.execute("SELECT tier, count(*) FROM code_edge GROUP BY tier").fetchall())
    relations = {}
    for rel, tier, count in con.execute("SELECT rel, tier, count(*) FROM code_edge GROUP BY rel, tier ORDER BY rel, tier"):
        relations.setdefault(rel, {})[tier] = count
    errors = con.execute("SELECT count(*) FROM code_file WHERE error IS NOT NULL").fetchone()[0]
    result = {"indexed": True, "files": counts["code_file"], "symbols": counts["code_symbol"] - counts["code_file"],
              "edges": counts["code_edge"], "notes": counts["code_note"], "parse_errors": errors, "tiers": tiers,
              "relations": relations}
    stale = [row[0] for row in con.execute("SELECT path FROM code_file WHERE stale_parse=1 ORDER BY path LIMIT 20")]
    if stale:
        result["stale_parse"] = stale
    coverage = meta_get(con, "coverage")
    if coverage:
        result["coverage"] = json.loads(coverage)
    head = meta_get(con, "head")
    if head:
        result["head"] = head
    return result


def coverage_line(con):
    """One line: what the code layer reads and what it cannot (so an empty answer is not read as
    'nothing depends on this')."""
    raw = meta_get(con, "coverage")
    if not raw:
        return None
    coverage = json.loads(raw)
    parts = []
    for lang, row in sorted(coverage.get("languages", {}).items()):
        text = f"{lang} {row.get('indexed', 0)}/{row.get('tracked', 0)}"
        extras = [f"{row[key]} {label}" for key, label in (("parse_errors", "unparsed"), ("stale", "stale"),
                                                             ("generated", "generated")) if row.get(key)]
        parts.append(text + (f" ({', '.join(extras)})" if extras else ""))
    line = "indexed: " + (", ".join(parts) or "nothing")
    missing = coverage.get("not_indexed") or {}
    if missing:
        line += "; not indexed (unsupported): " + ", ".join(f"{lang} {count}" for lang, count in sorted(missing.items()))
    if coverage.get("vendored"):
        line += f"; vendored/minified skipped: {coverage['vendored']}"
    if coverage.get("over_limit"):
        line += f"; over the {MAX_FILES}-file limit: {coverage['over_limit']}"
    return line


def indexed_head(con):
    """The commit the code layer was last indexed at (None before the first index)."""
    return meta_get(con, "head") if available(con) else None


def freshness(con, repo):
    """{"indexed_head", "head", "stale"}: whether HEAD moved since the code layer was indexed."""
    indexed = indexed_head(con)
    head = git_head(repo)
    return {"indexed_head": indexed, "head": head, "stale": bool(indexed and head and indexed != head)}


def file_state(con, path):
    row = con.execute("SELECT lang, error, stale_parse, generated FROM code_file WHERE path=?", (path,)).fetchone()
    if not row:
        return None
    state = {"lang": row[0]}
    if row[1]:
        state["error"] = row[1]
    if row[2]:
        state["stale_parse"] = True
    if row[3]:
        state["generated"] = True
    return state


def symbols_of(con, path):
    return [dict(zip(("id", "name", "kind", "line", "end_line", "doc"), row)) for row in con.execute(
        "SELECT id, qualname, kind, line, end_line, doc FROM code_symbol WHERE path=? AND kind != 'module' ORDER BY line",
        (path,))]


def python_modules(con):
    """Module name -> files, with the same package-boundary roots the resolver uses."""
    python = [row[0] for row in con.execute("SELECT path FROM code_file WHERE lang='python'")]
    packages = package_directories(python)
    modules = {}
    for path in python:
        for name in module_aliases(path, packages):
            modules.setdefault(name, set()).add(path)
    return modules


def find(con, name):
    """Symbols a name can mean: an exact id or qualified name, a dotted module path
    (`pkg.mod.Class.method`), or a bare name."""
    columns = ("id", "path", "name", "kind", "line")
    rows = con.execute("SELECT id, path, qualname, kind, line FROM code_symbol WHERE kind != 'module' AND "
                       "(id = ? OR qualname = ? OR name = ?) ORDER BY id", (name, name, name.rsplit(".", 1)[-1])).fetchall()
    exact = [row for row in rows if row[0] == name or row[2] == name]
    if exact:
        return [dict(zip(columns, row)) for row in exact]
    if "." in name and "::" not in name:
        parts = name.split(".")
        modules = python_modules(con)
        for size in range(len(parts) - 1, 0, -1):
            files = modules.get(".".join(parts[:size]), set())
            qualname = ".".join(parts[size:])
            found = [con.execute("SELECT id, path, qualname, kind, line FROM code_symbol WHERE id=?",
                                 (f"{path}::{qualname}",)).fetchone() for path in sorted(files)]
            found = [row for row in found if row]
            if found:
                return [dict(zip(columns, row)) for row in found]
    return [dict(zip(columns, row)) for row in rows if row[2].rsplit(".", 1)[-1] == name.rsplit(".", 1)[-1]
            and "." not in name]


# ---------------------------------------------------------------- queries: impact

def file_seeds(con, path):
    return ["file:" + path] + [row[0] for row in con.execute("SELECT id FROM code_symbol WHERE path=?", (path,))]


def escape_like(text):
    return text.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")


def overridden(con, cls, name, depth=0, seen=None):
    """Methods of `cls`'s bases (transitively) that a method named `name` overrides: a call
    bound to one of them can run the override at runtime."""
    seen = set() if seen is None else seen
    found = []
    if depth >= MAX_MRO or cls in seen:
        return found
    seen.add(cls)
    for (base,) in con.execute("SELECT dst FROM code_edge WHERE src=? AND rel='inherits'", (cls,)).fetchall():
        candidate = f"{base}.{name}"
        if con.execute("SELECT 1 FROM code_symbol WHERE id=?", (candidate,)).fetchone():
            found.append(candidate)
        found.extend(overridden(con, base, name, depth + 1, seen))
    return found


def symbol_seeds(con, symbol_id):
    """A symbol plus what changing it also changes: a class's members, and for a method the base
    methods it overrides (their callers may be calling it)."""
    seeds = [symbol_id]
    row = con.execute("SELECT path, name, qualname, kind, parent FROM code_symbol WHERE id=?", (symbol_id,)).fetchone()
    if not row:
        return seeds
    path, name, qualname, kind, parent = row
    if kind == "class":
        seeds.extend(found[0] for found in con.execute(
            "SELECT id FROM code_symbol WHERE path=? AND qualname LIKE ? ESCAPE '\\' ORDER BY id",
            (path, escape_like(qualname) + ".%")))
    elif kind == "method" and parent:
        seeds.extend(overridden(con, parent, name))
    return seeds


def start_seeds(con, target):
    """(seeds, origin files) for a file path, `file:PATH`, or a symbol id."""
    if target.startswith("file:"):
        target = target[len("file:"):]
    if "::" in target:
        return symbol_seeds(con, target), {target.split("::", 1)[0]}
    return file_seeds(con, target), {target}


def walk(con, seeds, origins, depth=2, limit=60):
    """Graphify's affected_nodes: a reverse breadth-first walk over imports, calls, inheritance,
    uses, and indirect references, reporting each dependent file once (at its shallowest depth)
    with the site that uses the target (file:line), not where the target is defined. A use from
    module level (`file:` source) affects the whole file; a use from a symbol carries on from that
    symbol only, so unrelated code in the same file is not dragged in."""
    results, visited = {}, set(seeds)
    frontier = list(seeds)
    seed_cache = {}
    marks_rel = ",".join("?" * len(WALKED))
    for level in range(1, max(1, min(int(depth), MAX_DEPTH)) + 1):
        following = []
        for start in range(0, len(frontier), 400):
            part = frontier[start:start + 400]
            marks = ",".join("?" * len(part))
            for src, rel, dst, src_path, line, confidence, tier, sites in con.execute(
                    f"SELECT src, rel, dst, src_path, line, confidence, tier, sites FROM code_edge WHERE dst IN ({marks}) "
                    f"AND rel IN ({marks_rel}) ORDER BY src_path, line", (*part, *WALKED)):
                if src_path not in origins:
                    row = results.get(src_path)
                    if row is None:
                        row = results[src_path] = {
                            "file": src_path, "via": rel, "target": dst, "site": f"{src_path}:{line}", "depth": level,
                            "confidence": confidence, "tier": tier, "test": is_test(src_path), "sites": sites,
                            "callers": []}
                    if not src.startswith("file:") and src not in row["callers"] and len(row["callers"]) < 20:
                        row["callers"].append(src)
                if src not in seed_cache:
                    seed_cache[src] = file_seeds(con, src_path) if src.startswith("file:") else symbol_seeds(con, src)
                for seed in seed_cache[src]:
                    if seed not in visited:
                        visited.add(seed)
                        following.append(seed)
        frontier = following
        if not frontier:
            break
    ordered = sorted(results.values(), key=lambda row: (row["depth"], row["test"], row["file"]))
    return ordered[:limit], len(ordered)


def public_rows(rows):
    return [{key: value for key, value in row.items() if key != "callers"} for row in rows]


def impact(con, target, depth=2, limit=60):
    """Who depends on a file or symbol, with the line that uses it."""
    seeds, origins = start_seeds(con, target)
    rows, total = walk(con, seeds, origins, depth, limit)
    return public_rows(rows), total


def dependents(con, path, limit=6):
    rows, _ = impact(con, path, depth=1, limit=limit)
    return rows


def imports_of(con, path):
    return [row[0] for row in con.execute(
        "SELECT DISTINCT dst_path FROM code_edge WHERE rel='imports' AND src_path=? ORDER BY dst_path", (path,))]


def notes_for(con, paths, limit=6):
    found = []
    for path in paths:
        found.extend(dict(zip(("path", "line", "tag", "text"), row)) for row in con.execute(
            "SELECT path, line, tag, text FROM code_note WHERE path=? ORDER BY line", (path,)))
    order = {tag: index for index, tag in enumerate(("WHY", "RATIONALE", "IMPORTANT", "SAFETY", "WARNING", "HACK",
                                                     "NOTE", "FIXME", "TODO"))}
    found.sort(key=lambda row: (order.get(row["tag"], 99), row["path"], row["line"]))
    return found[:limit]


# ---------------------------------------------------------------- queries: change sets and tests

REVISION = re.compile(r"[\w./@{}~^:+-]+")
HUNK = re.compile(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@")


def diff_hunks(repo, rev=None):
    """{path: [(first, last, deletion) new-side line ranges] or None for the whole file}: the working tree
    (staged or not) against `rev` (HEAD), with untracked readable files as wholly new."""
    rev = rev or "HEAD"
    if rev.startswith("-") or not REVISION.fullmatch(rev):
        raise ValueError(f"not a revision: {rev!r}")
    output = git_lines(repo, "-c", "core.quotepath=off", "diff", "-U0", "--no-color", "--no-ext-diff", "--no-renames",
                       rev, "--", timeout=60)
    if output is None:
        if rev != "HEAD" or git_head(repo) is not None:
            raise ValueError(f"git could not diff against {rev!r}")
        listing = list_tracked(repo) or []  # No commit yet: everything tracked is new.
        hunks = {path: None for path in listing if language(path) and not vendored(path)}
    else:
        hunks = parse_diff(output)
    for path in (git_lines(repo, "ls-files", "--others", "--exclude-standard", "-z") or "").split("\0"):
        if path and language(path) and not vendored(path) and not path.startswith(".improve/"):
            hunks[path] = None
    return hunks


def parse_diff(output):
    hunks, current, old = {}, None, None
    for line in output.splitlines():
        if line.startswith("--- "):
            old = line[6:] if line.startswith("--- a/") else None
        elif line.startswith("+++ "):
            if line[4:] == "/dev/null":
                current = None
                if old:
                    hunks[old] = None  # Deleted: everything that used it is affected.
            else:
                current = line[6:] if line.startswith("+++ b/") else line[4:]
                hunks.setdefault(current, [])
        elif line.startswith("@@") and current is not None and hunks.get(current) is not None:
            match = HUNK.match(line)
            if match:
                first, count = int(match.group(1)), int(match.group(2) or 1)
                # A pure deletion sits between `first` and `first + 1`: both neighbours count.
                hunks[current].append((first, first + 1, True) if count == 0 else (first, first + count - 1, False))
    return hunks


def current_definitions(con, repo, path):
    """(spans, lines, ids) for the file as it is now on disk: (first line, last line, symbol id)
    per definition, the file's lines, and every symbol id it defines. When the file does not
    parse at the moment, the index's ranges and no lines or ids."""
    lang = language(path)
    target = Path(repo) / path
    if lang and target.is_file() and not target.is_symlink():
        try:
            source = target.read_text(encoding="utf-8")
            symbols = extract(path, lang, source)["symbols"]
            spans = [(row[4], row[5], row[0]) for row in symbols if row[3] != "module" and row[5]]
            return spans, source.splitlines(), {row[0] for row in symbols}
        except (SyntaxError, ValueError, RecursionError, UnicodeDecodeError, OSError):
            pass
    spans = [(row[0], row[1], row[2]) for row in con.execute(
        "SELECT line, end_line, id FROM code_symbol WHERE path=? AND kind != 'module' AND end_line IS NOT NULL",
        (path,))]
    return spans, None, None


def insignificant(lines, line):
    """A blank or comment-only line outside every definition changes nothing that can break."""
    if lines is None or not 1 <= line <= len(lines):
        return False
    text = lines[line - 1].strip()
    return not text or text.startswith(("#", "//"))


def changed_symbols(spans, lines, ranges):
    """Map changed line ranges to the innermost definition containing each line. None when a
    changed line is module-level code (the whole file counts)."""
    changed = []

    def innermost(line):
        inside = [(end - start, symbol) for start, end, symbol in spans if start <= line <= end]
        return min(inside)[1] if inside else None

    for first, last, deletion in ranges:
        if deletion:
            # Lines were removed between `first` and `first + 1`: a definition around either
            # neighbour lost them; with neither inside one, module-level code was removed.
            hits = [symbol for symbol in (innermost(first), innermost(first + 1)) if symbol]
            if not hits:
                return None
        else:
            if last - first > 5000:
                return None
            hits = []
            for line in range(max(1, first), last + 1):
                symbol = innermost(line)
                if symbol is None:
                    if insignificant(lines, line):
                        continue
                    return None
                hits.append(symbol)
        for symbol in hits:
            if symbol not in changed:
                changed.append(symbol)
    return changed


def change_set(con, repo, rev=None):
    """(changes, seeds, origin files): what the working tree changed against `rev`. A definition
    that vanished from a file (deleted or renamed) counts as changed: its callers break."""
    changes, seeds, origins = [], [], set()
    for path, ranges in sorted(diff_hunks(repo, rev).items()):
        if not language(path) or vendored(path):
            continue
        origins.add(path)
        symbols = None
        if ranges is not None and (Path(repo) / path).is_file():
            spans, lines, current = current_definitions(con, repo, path)
            symbols = changed_symbols(spans, lines, ranges)
            if symbols is not None and current is not None:
                symbols.extend(row[0] for row in con.execute(
                    "SELECT id FROM code_symbol WHERE path=? AND kind != 'module' ORDER BY line", (path,))
                    if row[0] not in current and row[0] not in symbols)
        if symbols is None:
            changes.append({"file": path, "whole_file": True})
            seeds.extend(file_seeds(con, path))
        elif symbols:
            entry = {"file": path, "symbols": symbols[:20]}
            if len(symbols) > 20:
                entry["more"] = len(symbols) - 20
            changes.append(entry)
            for symbol in symbols:
                seeds.extend(symbol_seeds(con, symbol))
    return changes, list(dict.fromkeys(seeds)), origins


def changed_impact(con, repo, rev=None, depth=2, limit=60):
    """Impact of everything the working tree changed against `rev` (default HEAD, untracked files
    included): the changed symbols, every dependent, and the tests among them."""
    changes, seeds, origins = change_set(con, repo, rev)
    rows, total = walk(con, seeds, origins, depth, limit)
    tests = sorted({change["file"] for change in changes if is_test(change["file"])}
                   | {row["file"] for row in rows if row["test"]})
    return {"rev": rev or "HEAD", "changed": changes, "total": total, "shown": len(rows),
            "dependents": public_rows(rows), "tests": tests}


def test_runner(repo, con):
    """How this repository runs tests, per ecosystem (for ready-to-run hints)."""
    repo = Path(repo)
    runner = {}
    texts = []
    for name in ("pyproject.toml", "setup.cfg", "tox.ini", "pytest.ini", "requirements-dev.txt", "requirements.txt"):
        with contextlib.suppress(OSError):
            if (repo / name).is_file():
                texts.append((repo / name).read_text(errors="replace")[:200_000])
    has_conftest = bool(con.execute("SELECT 1 FROM code_file WHERE path='conftest.py' OR path LIKE '%/conftest.py' LIMIT 1")
                        .fetchone())
    runner["python"] = "pytest" if has_conftest or (repo / "pytest.ini").is_file() or any("pytest" in text for text in texts) \
        else "unittest"
    package = repo / "package.json"
    text = ""
    with contextlib.suppress(OSError):
        text = package.read_text(errors="replace")[:200_000] if package.is_file() else ""
    runner["script"] = next((tool for tool in ("vitest", "jest", "mocha") if tool in text), "npm")
    runner["jvm"] = "gradle" if any((repo / name).is_file() for name in ("build.gradle", "build.gradle.kts")) else \
        "maven" if (repo / "pom.xml").is_file() else None
    return runner


MAX_HINT = 150  # Output cells longer than 160 characters are cut, and a cut command cannot run.


def run_hint(path, tests, runner):
    """A command that runs just these tests (the whole file when naming them would be too long)."""
    lang = language(path)
    names = [test.split("::", 1)[1] for test in tests]
    if lang == "python":
        if runner.get("python") == "pytest":
            focused = "python -m pytest " + " ".join(f"{path}::{name.replace('.', '::')}" for name in names[:5])
            return focused if names and len(focused) <= MAX_HINT else f"python -m pytest {path}"
        directory, file_name = posixpath.split(path)
        hint = f"python -m unittest discover -s {directory or '.'} -p {file_name}"
        return hint + (f" -k {names[0].rsplit('.', 1)[-1]}" if len(names) == 1 else "")
    if lang in ("javascript", "typescript"):
        tool = runner.get("script")
        return {"vitest": f"npx vitest run {path}", "jest": f"npx jest {path}", "mocha": f"npx mocha {path}"}.get(
            tool, f"npm test -- {path}")
    if lang == "go":
        return f"go test ./{posixpath.dirname(path) or '.'}"
    if lang in ("java", "kotlin"):
        stem = posixpath.splitext(posixpath.basename(path))[0]
        return {"gradle": f"gradle test --tests '*{stem}'", "maven": f"mvn -Dtest={stem} test"}.get(runner.get("jvm"))
    if lang == "ruby":
        return f"bundle exec rspec {path}" if path.endswith("_spec.rb") else f"ruby -Itest {path}"
    return None


def looks_like_test(symbol_id):
    qualname = symbol_id.split("::", 1)[1]
    parts = qualname.split(".")
    return parts[-1].startswith("test") or (len(parts) == 1 and parts[0].startswith("Test"))


def tests_for(con, repo, seeds, origins, depth=3, limit=20):
    """Test files that reach the seeds through calls, imports, uses (including pytest fixtures
    from conftest.py), ranked by distance, each with a command that runs just them."""
    rows, _ = walk(con, seeds, origins, depth, limit=100_000)
    runner = test_runner(repo, con)
    found = [{"file": path, "distance": 0, "via": "changed", "tests": [], "run": run_hint(path, [], runner)}
             for path in sorted(origins) if is_test(path)]
    for row in rows:
        if not row["test"]:
            continue
        tests = [caller for caller in row["callers"] if looks_like_test(caller)]
        entry = {"file": row["file"], "distance": row["depth"], "via": row["via"], "site": row["site"],
                 "tests": tests[:10], "run": run_hint(row["file"], tests, runner)}
        found.append({key: value for key, value in entry.items() if value not in (None, [])})
    return found[:limit], len(found)


# ---------------------------------------------------------------- queries: search

IDENTIFIER_PART = re.compile(r"[A-Z]+(?=[A-Z][a-z])|[A-Z]?[a-z]+|[A-Z]+|\d+")
TEST_WORDS = frozenset(("test", "tests", "spec", "specs", "fixture", "fixtures", "conftest", "mock"))
DOC_SUFFIXES = (".md", ".rst", ".txt")
SEARCH_STOP = frozenset(("the", "a", "an", "of", "to", "in", "for", "and", "or", "is", "how", "what", "where",
                         "does", "do", "with", "on", "by", "it", "this", "that"))
FIELD_WEIGHTS = (3.0, 1.5, 1.0)  # name, qualified name and path, docstring or note text
DEMOTED = 0.35


def words_of(text):
    """Identifier-aware tokens: `retry_upload` -> retry, upload; `UploadManager` -> upload, manager."""
    found = []
    for chunk in re.findall(r"[A-Za-z0-9]+", text or ""):
        for part in IDENTIFIER_PART.findall(chunk):
            word = part.lower()
            if len(word) > 3 and word.endswith("s") and not word.endswith("ss"):
                word = word[:-1]
            found.append(word)
    return found


def search(con, text, limit=10):
    """Code search over symbol names, qualified names, paths, docstrings, and code notes:
    IDF-weighted, every query word counted once at its best field, tests and docs demoted unless
    the query is about tests. Returns (rows, suggestions); suggestions only when nothing matched."""
    query = [word for word in dict.fromkeys(words_of(text)) if word not in SEARCH_STOP] or words_of(text)
    if not query:
        return [], []
    documents, cache = [], {}

    def words(text):
        if text not in cache:
            cache[text] = frozenset(words_of(text))
        return cache[text]

    for symbol_id, path, name, qualname, kind, line, doc in con.execute(
            "SELECT id, path, name, qualname, kind, line, doc FROM code_symbol WHERE kind != 'module'"):
        documents.append(({"id": symbol_id, "kind": kind, "line": line, "doc": doc}, path,
                          (words(name), words(qualname) | words(posixpath.splitext(path)[0]), words(doc or ""))))
    for path, line, tag, note in con.execute("SELECT path, line, tag, text FROM code_note"):
        documents.append(({"id": f"{path}:{line}", "kind": "note", "line": line, "doc": f"{tag}: {note}"}, path,
                          (frozenset(), words(posixpath.splitext(path)[0]), words(note))))
    total = len(documents) or 1
    frequency = dict.fromkeys(query, 0)
    for _, _, fields in documents:
        present = fields[0] | fields[1] | fields[2]
        for word in query:
            if word in present:
                frequency[word] += 1
    weights = {word: math.log((total + 1) / (frequency[word] + 0.5)) for word in query}
    about_tests = bool(set(query) & TEST_WORDS)
    scored = []
    for row, path, fields in documents:
        score, matched = 0.0, 0
        for word in query:
            best = max((weight for field, weight in zip(fields, FIELD_WEIGHTS) if word in field), default=0.0)
            if best:
                score += best * weights[word]
                matched += 1
        if not matched:
            continue
        score *= (matched / len(query)) ** 2
        if not about_tests and (is_test(path) or path.endswith(DOC_SUFFIXES)):
            score *= DEMOTED
        scored.append((round(score, 3), row))
    scored.sort(key=lambda item: (-item[0], item[1]["id"]))
    rows = [{**row, "score": score} for score, row in scored[:limit]]
    for row in rows:
        if not row["doc"]:
            row.pop("doc")
    if rows:
        return rows, []
    vocabulary = set()
    for _, _, fields in documents:
        vocabulary |= fields[0] | fields[1]
    suggestions = []
    for word in query:
        suggestions.extend(match for match in difflib.get_close_matches(word, sorted(vocabulary), n=3, cutoff=0.7)
                           if match not in suggestions)
    names = sorted({row["id"].split("::", 1)[-1] for row, _, _ in documents if row["kind"] != "note"})
    suggestions.extend(match for match in difflib.get_close_matches(text.replace(" ", "_"), names, n=3, cutoff=0.6)
                       if match not in suggestions)
    return [], suggestions[:8]


